r"""The bookmarklet is generated by string concatenation, so nothing validated it.

`tests/test_template_js.py` runs `node --check` over every inline `<script>` in
`tools/templates/`, which proves the GENERATOR parses. It says nothing about the
`javascript:` URL that generator builds one character at a time — and that string is the
code that actually runs in people's browsers. A syntax error in it produces a bookmarklet
that silently does nothing, on a link already dragged into a bookmarks bar.

This lifts the `var bm = …` expression out of the macro, evaluates it in node with the
template's two variables supplied, and then checks the RESULT parses and behaves.

**The behaviour it pins is the reported bug.** From a live log, with the server mid-ingest:

    20:36:24  beacon issued (its own &t= cache-buster says so)
    ~20:36:30 the 6s timer fires -> window.open is blocked, because a setTimeout carries
              no user gesture, so it falls through to location.href and navigates the
              ARTICLE tab to /save
    20:36:52  POST /chat/send -> 200 in 38290ms
    20:37:01  autolink: linked 49 title(s) (44.4s, 15688 titles checked)
    20:37:02  both requests answer: beacon 200, navigation 302

Reported as *"it loads a blank page pointing at lobotomy, then eventually snaps back to
the actual article"* — that blank page is the navigation, the snap back is its redirect —
and *"duplicate tabs open to the nyt stories, and then 2 identical items appear"*.

**A slow server is not a blocked beacon.** `onerror` means the request never arrived and
there is something to recover from, so it keeps the fallback. A timeout means we do not
know, and acting as though it failed is what opened the tab, navigated the reader away,
and saved the article twice. The timer now only says "still saving".
"""
import json
import re
import shutil
import subprocess
import sys
import unittest
from pathlib import Path

MACRO = Path(__file__).resolve().parent.parent / "tools" / "templates" / "bookmarklet_macro.html"
NODE = shutil.which("node")


def _bookmarklet_body():
    """The generated `javascript:` body, with the macro's two variables filled in."""
    src = MACRO.read_text(encoding="utf-8")
    i = src.index("var bm = 'javascript:(function(){'")
    j = src.index('";', i) + 2
    expr = src[i:j].split("var bm = ", 1)[1].rstrip().rstrip(";")
    js = (
        "const base = " + json.dumps("https://lobotomy.example") + ";\n"
        "const key = " + json.dumps("TESTKEY") + ";\n"
        "const bm = " + expr + ";\n"
        "const body = bm.replace(/^javascript:/, '');\n"
        "new Function(body);\n"                       # throws on a syntax error
        "process.stdout.write(body);\n"
    )
    out = subprocess.run([NODE, "-e", js], capture_output=True, text=True)
    if out.returncode != 0:
        raise AssertionError("the generated bookmarklet does not parse:\n" + out.stderr)
    return out.stdout


@unittest.skipUnless(NODE, "node is not installed")
class GeneratedBookmarkletTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.body = _bookmarklet_body()

    def _deadline(self):
        """The LAST `setTimeout`, which is the deadline.

        The first is the toast's own two-second remove timer, and reading that one is
        how the first draft of this module asserted against the wrong code: two tests
        failed for the wrong reason and `test_the_guard_still_fires_once` PASSED, on
        `d=1` text belonging to the `f()` that happens to follow it.
        """
        i = self.body.rindex("setTimeout")
        seg = self.body[i:self.body.index("i.src=", i)]
        # If the deadline is ever deleted, rindex lands on the toast's timer and every
        # assertion below would pass on code it was not aimed at.
        self.assertNotIn("e.remove()", seg,
                         "the deadline timer is gone; this is the toast's own timer")
        return seg

    def test_it_parses(self):
        """`new Function(body)` inside the lift already threw if not; this names it."""
        self.assertGreater(len(self.body), 200)

    def test_it_targets_the_save_route_with_the_key(self):
        self.assertIn("/save?key=", self.body)
        self.assertIn("TESTKEY", self.body)
        self.assertIn("beacon=1", self.body)

    def test_the_timer_does_not_navigate_or_open_a_tab(self):
        """**The bug.** The timeout branch used to call `f()`, whose first move is
        `window.open` — blocked, because a setTimeout has no user gesture — and whose
        fallback is `location.href`, which yanks the reader out of the article."""
        timer = self._deadline()
        self.assertNotIn("location.href", timer,
                         "the timeout still navigates the article tab away")
        self.assertNotIn("window.open", timer,
                         "the timeout still tries to open a tab")
        self.assertNotIn("f()", timer, "the timeout still calls the blocked-beacon path")

    def test_the_timer_says_something_rather_than_nothing(self):
        timer = self._deadline()
        self.assertIn("t(", timer, "a timeout reports nothing at all to the reader")
        self.assertIn("Still saving", self.body)

    def test_a_blocked_beacon_still_falls_back(self):
        """`onerror` is the case where the request genuinely never arrived — a page's
        img-src CSP, which Wikipedia's does. That one must still recover."""
        self.assertIn("i.onerror=f", self.body)
        f_body = self.body[self.body.index("function f()"):self.body.index("var i=new Image")]
        self.assertIn("window.open", f_body)
        self.assertIn("location.href", f_body)
        self.assertIn("close=1", f_body)

    def test_the_deadline_is_long_enough_for_a_busy_server(self):
        """6 seconds against a server measured holding a request for 38 while it ran a
        44-second autolink. The server answers a beacon before capturing now, so this is
        a backstop rather than the mechanism — but 6s was shorter than the thing it was
        waiting for."""
        m = re.search(r"\},(\d+)\);$", self._deadline())
        self.assertIsNotNone(m, self._deadline())
        self.assertGreaterEqual(int(m.group(1)), 15000)

    def test_the_guard_still_fires_once(self):
        """`d` is what stops the beacon's success and the fallback both reporting. Every
        branch has to set it, or two toasts appear — or worse, two saves."""
        segs = {"the deadline": self._deadline()}
        for branch in ("i.onload", "function f()"):
            i = self.body.index(branch)
            segs[branch] = self.body[i:i + 60]
        for name, seg in segs.items():
            self.assertIn("d=1", seg, f"{name} does not take the once-only guard")
            self.assertIn("if(d)return", seg, f"{name} does not check the guard")

    def test_the_toast_is_removed_again(self):
        self.assertIn("e.remove()", self.body)


class TheLiftReachesTheCodeTest(unittest.TestCase):
    """If the lift stops finding the expression it must fail loudly, not pass vacuously —
    the same trap as a fixture that cannot reach the code it names."""

    def test_the_anchor_is_present(self):
        src = MACRO.read_text(encoding="utf-8")
        self.assertIn("var bm = 'javascript:(function(){'", src,
                      "the lift's anchor is gone; every assertion above is vacuous")


if __name__ == "__main__":
    unittest.main()
